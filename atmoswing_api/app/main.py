import logging
from contextlib import asynccontextmanager
from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse
from starlette.exceptions import HTTPException as StarletteHTTPException
from atmoswing_api import cache
from atmoswing_api.config import get_settings
from atmoswing_api.app.utils.logger import configure_logging
from atmoswing_api.__version__ import __version__
from atmoswing_api.app.limiter import RateLimitMiddleware
from atmoswing_api.app.routes import meta, forecasts, aggregations, docs

configure_logging(get_settings())
logger = logging.getLogger(__name__)


@asynccontextmanager
async def lifespan(app: FastAPI):
    # Check Redis from the serving event loop and log whether caching is enabled
    await cache.check_connection()
    yield
    await cache.close()


app = FastAPI(
    lifespan=lifespan,
    title="AtmoSwing Web Forecast API",
    description="API to provide forecasts generated by AtmoSwing.",
    version=__version__,
)

# Rate limiting (see app/limiter.py)
app.add_middleware(RateLimitMiddleware)

